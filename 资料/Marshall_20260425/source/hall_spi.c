/* FUNCTION ************************************************************************************************************
 *
 * Function Name : Hall_CLK_Command_SET
 * Description   : Set different commands by pulling the CKL PIN up and down.
 *
 * END ****************************************************************************************************************/
void Hall_CLK_Command_SET(unsigned short high_delay, unsigned short low_delay)
{
	//------------------------------------------------------------------------------------------
	/* Disable global interrupt */
	uint32_t regPrimask = DisableGlobalIRQ();
	//------------------------------------------------------------------------------------------
	/* Set all hall sensor SPI clock as GPIO */
	SET_ALLCLKPins_AS_GPIO();
	SET_ALLCLKPins_AS_OUTPUT();
	//------------------------------------------------------------------------------------------
	/* Set all hall sensor SPI clock as high level */
	SET_ALLCLKPins_HIGH();
	//------------------------------------------------------------------------------------------
	hall_mcu_delay_us(high_delay);
	//------------------------------------------------------------------------------------------
	/* Set all hall sensor SPI clock as low level */
	SET_ALLCLKPins_LOW();
	//------------------------------------------------------------------------------------------
	hall_mcu_delay_us(low_delay);
	//------------------------------------------------------------------------------------------
	/* Set all hall sensor SPI clock as SPI clock */
	SET_ALLCLKPins_AS_CLK();
	//------------------------------------------------------------------------------------------
	/* Enable global interrupt */
	EnableGlobalIRQ(regPrimask);
}
