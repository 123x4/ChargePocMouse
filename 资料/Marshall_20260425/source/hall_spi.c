/* FUNCTION ************************************************************************************************************
 *
 * Function Name : Hall_Rawdata_ConvertTo_Section
 * Description   : Convert hall raw data to component segment;
 *
 * END ****************************************************************************************************************/
void Group1_Baseline_Calibration(uint8_t Keyindex)
{
	//uint8_t Adjust_Value;
	//------------------------------------------------------------------------------------------
	if(DMA_SPI_RX_1_Buffer_Store[Keyindex] > 0xFFFF)
	{
		return;
	}
	if(LED_HIGHLIGHT_Buffer[0][Keyindex] != 0x95)
	{
		return;
	}
	if(DMA_SPI_RX_1_Buffer_Store[Keyindex] > 9000)
	{
		return;
	}

	if(Tem_timer_COUNT_SPI0[Keyindex] < 10)
	{
		Tem_timer_CNT_SPI0[Keyindex]++;
	}

	if(DMA_SPI_RX_1_Buffer_Store[Keyindex] > BaslineTopDefault)
	{
		//--------------------------------------------------------------------------------------
		Top_Timer_CNT1_SPI0[Keyindex]++;
		//上电的校准，方便top快速达到raw data这个范围
		if(Hall_PowerON_BaselineCal)
		{
			//--------------------------------------------------------------------------------------
			if(Top_Timer_CNT1_SPI0[Keyindex] >= 1)
			{
				//------------------------------------------------------------------------------------------
				Top_Timer_CNT1_SPI0[Keyindex] = 0;
				//------------------------------------------------------------------------------------------
				if(DMA_SPI_RX_1_Buffer_Store[Keyindex] > (Baseline_Top_SPI0[Keyindex] + 8))
				{
					Baseline_Top_SPI0[Keyindex] += 5;
				}
				else if(Baseline_Top_SPI0[Keyindex] > (DMA_SPI_RX_1_Buffer_Store[Keyindex] + 8))
				{
					Baseline_Top_SPI0[Keyindex] -= 5;
				}
				//------------------------------------------------------------------------------------------
				if(Hall_PowerON_BaselineCal <= 1)
				{
					Top_Timer_CNT1_SPI0[Keyindex] = 0;
					Sample_Top_Sum1_SPI0[Keyindex] = 0;
					Top_Update_CNT1_SPI0[Keyindex] = 0;
					//----------------------------------------------------------------------------------------------------------------------------------------
					//Adjust_Value = Baseline_Bottom_Calibration_SPI0(Keyindex);
					//Baseline_Step_SPI0[Keyindex] = (uint16_t)((1 << 21) / (Baseline_Top_SPI0[Keyindex] - Baseline_Bottom_SPI0[Keyindex] - Adjust_Value));
					Baseline_Step_SPI0[Keyindex] = (Baseline_Top_SPI0[Keyindex] - Baseline_Bottom_SPI0[Keyindex] - Adjust_Value);
					//----------------------------------------------------------------------------------------------------------------------------------------
				}
			}
		}
		//之后要缓慢变化，不能再快速变化，不然当按键缓慢按下的时候，top也变会导致分段不对
		else
		{
			if(Top_Timer_CNT1_SPI0[Keyindex] >= 125)
			{
				Top_Timer_CNT1_SPI0[Keyindex] = 0;
				Sample_Top_Sum1_SPI0[Keyindex] += DMA_SPI_RX_1_Buffer_Store[Keyindex];
				Top_Update_CNT1_SPI0[Keyindex]++;

				if(Top_Update_CNT1_SPI0[Keyindex] == 8)
				{
					Top_Update_CNT1_SPI0[Keyindex] = 0;

					Sample_Top_Sum1_SPI0[Keyindex] >>= 3;

					if(Sample_Top_Sum1_SPI0[Keyindex] > (8 + Baseline_Top_SPI0[Keyindex]))
					{
						Top_Update_CNT2_SPI0[Keyindex] = 0;

						Top_Down_CNT1_SPI0[Keyindex] = 0;
						Top_UP_CNT_SPI0[Keyindex]++;
						if(Top_UP_CNT_SPI0[Keyindex] >= 10)
						{
							Top_UP_CNT_SPI0[Keyindex] = 0;

							Baseline_Top_SPI0[Keyindex] += 10;

							Baseline_variation_SPI0[Keyindex] += 10;

							Baseline_Step_SPI0[Keyindex] = (Baseline_Top_SPI0[Keyindex] - Baseline_Bottom_SPI0[Keyindex] - Adjust_Value);
						}

					}
					else if(Baseline_Top_SPI0[Keyindex] > Sample_Top_Sum1_SPI0[Keyindex])
					{
						Top_Update_CNT2_SPI0[Keyindex]++;

						if(Top_Update_CNT2_SPI0[Keyindex] == 16)
						{
							Top_Update_CNT2_SPI0[Keyindex] = 0;

							Top_Down_CNT_SPI0[Keyindex]++;
							Top_UP_CNT_SPI0[Keyindex] = 0;
							if(Top_Down_CNT_SPI0[Keyindex] >= 5)
							{
								Top_Down_CNT_SPI0[Keyindex] = 0;

								Baseline_Top_SPI0[Keyindex] -= 5;
								if(Baseline_variation_SPI0[Keyindex])
								{
									Baseline_variation_SPI0[Keyindex] -= 5;
								}
								Baseline_Step_SPI0[Keyindex] = (Baseline_Top_SPI0[Keyindex] - Baseline_Bottom_SPI0[Keyindex] - Adjust_Value);
							}
						}
					}
					else
					{
						Top_Down_CNT_SPI0[Keyindex] = 0;
						Top_UP_CNT_SPI0[Keyindex] = 0;
						Top_Update_CNT2_SPI0[Keyindex] = 0;
					}
					Sample_Top_Sum1_SPI0[Keyindex] = 0;
				}
			}
		}
	}
	else if(DMA_SPI_RX_1_Buffer_Store[Keyindex] < 250)
	{
		if(g_variableData.Gain_Buffer[0][Keyindex]< 0x0E)
		{
			g_variableData.Gain_Buffer[0][Keyindex]++;
		}
		Flag_has_gain_adjust = 1;

		Baseline_Bottom_SPI0[Keyindex] = BaslineBottomDefault;
		Baseline_Step_SPI0[Keyindex] = (Baseline_Top_SPI0[Keyindex] - Baseline_Bottom_SPI0[Keyindex] - Adjust_Value);
	}
	else if(DMA_SPI_RX_1_Buffer_Store[Keyindex] < BaslineBottomDefault)
	{

		if(Bottom_baseline_adjust_CNT_SPI0[Keyindex] < 128)
		{
			Bottom_baseline_adjust_CNT_SPI0[Keyindex]++;
		}

		if(Baseline_Bottom_SPI0[Keyindex] > (1000 + DMA_SPI_RX_1_Buffer_Store[Keyindex]))
		{
			Tem_timer_COUNT_SPI0[Keyindex] = 0;
			Tem_timer_CNT_SPI0[Keyindex] = 0;
			//------------------------------------------------------------------------------------------
			Baseline_Bottom_SPI0[Keyindex] = DMA_SPI_RX_1_Buffer_Store[Keyindex] + 400;
			//------------------------------------------------------------------------------------------
			Baseline_Step_SPI0[Keyindex] = (Baseline_Top_SPI0[Keyindex] - Baseline_Bottom_SPI0[Keyindex] - Adjust_Value);
			//------------------------------------------------------------------------------------------
		}
		else if(Baseline_Bottom_SPI0[Keyindex] > (50 + DMA_SPI_RX_1_Buffer_Store[Keyindex]))
		{
			if(Bottom_baseline_adjust_CNT_SPI0[Keyindex] < 128)
			{
				if(IF_adjust_flag_SPI0[Keyindex] == 0)
				{
					IF_adjust_flag_SPI0[Keyindex] = 1;
					//------------------------------------------------------------------------------------------
					Tem_timer_COUNT_SPI0[Keyindex] = 0;
					Tem_timer_CNT_SPI0[Keyindex] = 0;
					//------------------------------------------------------------------------------------------
					Baseline_Bottom_SPI0[Keyindex] = ((Baseline_Bottom_SPI0[Keyindex] + DMA_SPI_RX_1_Buffer_Store[Keyindex])>>1);
					//------------------------------------------------------------------------------------------
					Baseline_Step_SPI0[Keyindex] = (Baseline_Top_SPI0[Keyindex] - Baseline_Bottom_SPI0[Keyindex] - Adjust_Value);
					//------------------------------------------------------------------------------------------
				}
				else if((Bottom_baseline_adjust_CNT_SPI0[Keyindex]  & 0x1f) == 0)
				{
					//------------------------------------------------------------------------------------------
					Tem_timer_COUNT_SPI0[Keyindex] = 0;
					Tem_timer_CNT_SPI0[Keyindex] = 0;
					//------------------------------------------------------------------------------------------
					Baseline_Bottom_SPI0[Keyindex] = ((Baseline_Bottom_SPI0[Keyindex] + DMA_SPI_RX_1_Buffer_Store[Keyindex])>>1);
					//------------------------------------------------------------------------------------------
					Baseline_Step_SPI0[Keyindex] = (Baseline_Top_SPI0[Keyindex] - Baseline_Bottom_SPI0[Keyindex] - Adjust_Value);
					//------------------------------------------------------------------------------------------
				}
			}
		}
	}
	//------------------------------------------------------------------------------------------
	if(Tem_timer_CNT_SPI0[Keyindex] > 600000)
	{
		//------------------------------------------------------------------------------------------
		Tem_timer_COUNT_SPI0[Keyindex]++;
		Tem_timer_CNT_SPI0[Keyindex] = 0;
		//------------------------------------------------------------------------------------------
		if(Baseline_Bottom_SPI0[Keyindex] >= (BaslineBottomDefault + 400))
		{
			return;
		}
		//------------------------------------------------------------------------------------------
		Baseline_Bottom_SPI0[Keyindex] += 50;
		//------------------------------------------------------------------------------------------
		Baseline_Step_SPI0[Keyindex] = (Baseline_Top_SPI0[Keyindex] - Baseline_Bottom_SPI0[Keyindex] - Adjust_Value);
		//------------------------------------------------------------------------------------------
	}
	//------------------------------------------------------------------------------------------
}
