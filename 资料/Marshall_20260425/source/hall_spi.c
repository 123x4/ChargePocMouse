/* FUNCTION ************************************************************************************************************
 *
 * Function Name : Hall_Check_Rawdata_CRC
 * Description   : Hall sensor's raw data was used the highest two bit as CRC, its algorithm is use other bit for XOR.
 * Example: CRC0=D0^D2^D4^D6^D8^D10^D12, CRC1=D1^D3^D5^D7^D9^D11^D13, CRC1 is the highest bit, and CRC0 is the second highest bit, and D means the number of raw data's bit.
 * END ****************************************************************************************************************/
uint8_t Hall_Check_Rawdata_CRC_SPI0(uint8_t Keyindex)
{
	uint8_t The_highest_TwoBit = 0;
	uint8_t The_highest_SixBit = 0;
	uint8_t The_lowest_EightBit = 0;
	//------------------------------------------------------------------------------------------
	The_highest_TwoBit = ((DMA_SPI_RX_1_Buffer[Keyindex] & 0xC000)>>8);
	The_highest_SixBit =((DMA_SPI_RX_1_Buffer[Keyindex] & 0x3FFF)>>8);
	The_lowest_EightBit =(DMA_SPI_RX_1_Buffer[Keyindex] & 0x00FF);
	//------------------------------------------------------------------------------------------
	if(The_highest_TwoBit == ((BIT_Error[The_highest_SixBit]) ^ (BIT_Error[The_lowest_EightBit])))
	{
		return ROWDATA_CRC_SUCCESS;
		//------------------------------------------------------------------------------------------
	}
	else
	{
		return ROWDATA_CRC_ERROR;
	}
	//------------------------------------------------------------------------------------------
}
