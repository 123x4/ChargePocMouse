/* FUNCTION ************************************************************************************************************
 *
 * Function Name : HallSensor_INIT
 * Description   : Config hall sensor register.
 *
 * END ****************************************************************************************************************/
void HallSensor_INIT(void)
{
	uint8_t Hall_Initial_Fail_CNT = 0;
	//------------------------------------------------------------------------------------------
	/* After hall sensor power on, it should check FREQ firstly. if the FREQ is beyond of 80-176(this value is released by the vendor and we do not know why it is in this range),
	 * the hall sensor will be a bad IC and it should be fix by EE.
	 * */
	usb_echo("1\r\n");
	Hall_Initial_Fail_Flag = HALLChain_Check_FREQ_DETECH();
	usb_echo("2 \r\n");
	//------------------------------------------------------------------------------------------
	Hall_osc_calibrate();
	usb_echo("3 \r\n");
	//------------------------------------------------------------------------------------------
	Hall_set_mode_14bit();
	usb_echo("4 \r\n");
	//hall_mcu_delay_ms(1);
	//------------------------------------------------------------------------------------------
	Hall_Initial_Fail_CNT = 0;
	if(Hall_Initial_Fail_Flag)
	{
		//------------------------------------------------------------------------------------------
		#if UART_DEBUG
			#if 1
				usb_echo("CRC ERR, Try again.\r\n");
			#endif
		#endif
		//----------------------------------------------------------------------------------------------
		while((++Hall_Initial_Fail_CNT< 10) && (Hall_Initial_Fail_Flag == 1))
		{
			CRCErr_Hall_INIT_Again();
		}
		//----------------------------------------------------------------------------------------------
	}
	usb_echo("5 \r\n");
	//------------------------------------------------------------------------------------------
	Hall_set_pwm_period(Led_PWM_Period_Value);\
	usb_echo("6 \r\n");
	//hall_mcu_delay_ms(1);
	Hall_read_REG();
	//------------------------------------------------------------------------------------------
}

